const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");
export function descriptionMissing(n: WorkNode) {
  const missing: string[] = [];
  if (!n.clientId) missing.push("клиент результата");
  if (!n.purpose) missing.push("потребность/назначение");
  if (!n.inputs.length) missing.push("входы");
  if (n.inputs.some(i => !i.sourceId || !i.freshness)) missing.push("источники/актуальность входов");
  if (!n.procedure) missing.push("действия/процедура");
  if (!n.success) missing.push("критерии приёмки");
  if (!n.acceptorId) missing.push("принимающий");
  if (!n.resourceIds.length) missing.push("необходимые ресурсы");
  if (!n.rules && !n.constraints) missing.push("границы полномочий");
  // Design readiness deliberately does not require a live executor or connected API.
  return missing;
}
function table(nodes: WorkNode[]) {
  return [
    "| Код / постоянный ID | Пункт | Фактическая готовность | Пробелы | Проверяемое условие завершения |",
    "|---|---|---|---|---|",
    ...nodes.map(n => {
      const gaps = descriptionMissing(n);
      const readiness = gaps.length ? "Черновик описания" : "Готово к обсуждению, не утверждено";
      return `| ${cell(n.code)} / ${n.id} | ${cell(n.name)} | ${readiness}; ${n.detailState === "described" ? "описание есть" : "каркас"}. Исходный статус ${n.status} не равен приёмке полноты | ${cell([...gaps, ...(n.questions ? [n.questions] : [])].join("; ") || "Нужна содержательная проверка")} | Закрыты перечисленные пробелы и общий критерий раздела 3; явная приёмка версии |`;
    }),
  ].join("\n");
}
